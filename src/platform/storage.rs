use std::fs::{self, File};
use std::io::Write;
use std::path::{Path, PathBuf};

use crate::core::error::{AppError, AppResult};
use crate::core::model::AppState;
use crate::core::ports::StateRepository;
use crate::platform::win_util::{app_data_dir, atomic_replace_file};

/// File-backed `StateRepository` storing atomic JSON state and a standalone emergency recovery script.
pub struct FileStateRepository {
    state_path: PathBuf,
    recovery_path: PathBuf,
}

impl FileStateRepository {
    pub fn default_location() -> Self {
        Self::in_dir(app_data_dir())
    }

    pub fn in_dir(dir: PathBuf) -> Self {
        Self {
            state_path: dir.join("state.json"),
            recovery_path: dir.join("restore-all.ps1"),
        }
    }

    fn write_recovery_script(&self, state: &AppState) -> AppResult<()> {
        let all_tips: Vec<&str> = state.profiles.iter().map(|p| p.tip_id.as_str()).collect();
        if all_tips.is_empty() {
            return Ok(());
        }
        let joined = escape_ps_single_quoted(&all_tips.join(";"));
        let first = escape_ps_single_quoted(all_tips[0]);

        let script = format!(
            r#"# Emergency recovery script auto-generated by ToggleLang
# Restores all tracked keyboard layouts/IMEs in their original order via input.dll
$ErrorActionPreference = 'Stop'

Add-Type -TypeDefinition @"
using System;
using System.Runtime.InteropServices;
public static class ToggleLangRecovery {{
    [DllImport("input.dll", CharSet = CharSet.Unicode)]
    public static extern bool InstallLayoutOrTip(string psz, uint dwFlags);
    [DllImport("input.dll", CharSet = CharSet.Unicode)]
    public static extern bool SetDefaultLayoutOrTip(string psz, uint dwFlags);
}}
"@

$allTips = '{joined}'
$firstTip = '{first}'

# ILOT_CLEANINSTALL = 0x00000040
$ok = [ToggleLangRecovery]::InstallLayoutOrTip($allTips, 0x00000040)
if (-not $ok) {{
    throw "InstallLayoutOrTip failed for: $allTips"
}}
[void][ToggleLangRecovery]::SetDefaultLayoutOrTip($firstTip, 0x00000001)
Write-Host "Restored all layouts: $allTips" -ForegroundColor Green
"#
        );

        write_file_atomically(&self.recovery_path, script.as_bytes())
    }
}

impl StateRepository for FileStateRepository {
    fn load(&self) -> AppResult<Option<AppState>> {
        if !self.state_path.exists() {
            return Ok(None);
        }
        let content = fs::read_to_string(&self.state_path).map_err(|e| {
            AppError::Storage(format!("Failed to read {}: {e}", self.state_path.display()))
        })?;
        let state = serde_json::from_str(&content).map_err(|e| {
            AppError::Storage(format!(
                "Failed to parse {}: {e}",
                self.state_path.display()
            ))
        })?;
        Ok(Some(state))
    }

    fn save(&self, state: &AppState) -> AppResult<()> {
        let json = serde_json::to_string_pretty(state)
            .map_err(|e| AppError::Storage(format!("Failed to serialize state: {e}")))?;

        write_file_atomically(&self.state_path, json.as_bytes())?;
        // Recovery script generation is best-effort so a locked `.ps1` never blocks saving state.
        let _ = self.write_recovery_script(state);
        Ok(())
    }

    fn state_location(&self) -> String {
        self.state_path.display().to_string()
    }

    fn recovery_location(&self) -> Option<String> {
        self.recovery_path
            .exists()
            .then(|| self.recovery_path.display().to_string())
    }
}

/// Writes `bytes` to a PID-scoped temporary sibling file, flushes to disk, and atomically replaces `target`.
fn write_file_atomically(target: &Path, bytes: &[u8]) -> AppResult<()> {
    if let Some(parent) = target.parent() {
        fs::create_dir_all(parent).map_err(|e| {
            AppError::Storage(format!(
                "Failed to create directory {}: {e}",
                parent.display()
            ))
        })?;
    }

    let file_name = target
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("togglelang");
    let tmp_path = target.with_file_name(format!("{file_name}.{}.tmp", std::process::id()));

    let write_res = (|| -> AppResult<()> {
        let mut file = File::create(&tmp_path).map_err(|e| {
            AppError::Storage(format!("Failed to create {}: {e}", tmp_path.display()))
        })?;
        file.write_all(bytes).map_err(|e| {
            AppError::Storage(format!("Failed to write {}: {e}", tmp_path.display()))
        })?;
        file.sync_all().map_err(|e| {
            AppError::Storage(format!("Failed to flush {}: {e}", tmp_path.display()))
        })?;
        Ok(())
    })();

    if let Err(err) = write_res {
        let _ = fs::remove_file(&tmp_path);
        return Err(err);
    }

    if let Err(err) = atomic_replace_file(&tmp_path, target) {
        let _ = fs::remove_file(&tmp_path);
        return Err(err);
    }

    Ok(())
}

fn escape_ps_single_quoted(value: &str) -> String {
    value.replace('\'', "''")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::core::model::{LayoutProfile, ProfileKind};

    fn temp_test_dir(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("togglelang_{tag}_{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        dir
    }

    #[test]
    fn atomic_save_and_load_round_trip() {
        let dir = temp_test_dir("roundtrip");
        let repo = FileStateRepository::in_dir(dir.clone());
        assert_eq!(repo.load().unwrap(), None);

        let state = AppState {
            version: 1,
            tray_icon_mode: Default::default(),
            original_snapshot: vec!["0409:00000409".into()],
            profiles: vec![LayoutProfile {
                tip_id: "0409:00000409".into(),
                kind: ProfileKind::KeyboardLayout,
                langid: 0x0409,
                clsid: None,
                guid_profile: None,
                bcp47: "en-US".into(),
                short_badge: "ENG".into(),
                language_name: "English (United States)".into(),
                layout_name: "US".into(),
                enabled: true,
            }],
        };

        repo.save(&state).unwrap();
        let loaded = repo.load().unwrap().expect("saved state must load back");
        assert_eq!(loaded, state);

        let recovery_path = repo.recovery_location().expect("recovery script created");
        let ps1 = fs::read_to_string(recovery_path).unwrap();
        assert!(ps1.contains("$allTips = '0409:00000409'"));

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn reports_storage_error_on_corrupt_json() {
        let dir = temp_test_dir("corrupt");
        fs::create_dir_all(&dir).unwrap();
        fs::write(dir.join("state.json"), "{ invalid json").unwrap();

        let repo = FileStateRepository::in_dir(dir.clone());
        assert!(matches!(repo.load(), Err(AppError::Storage(_))));

        let _ = fs::remove_dir_all(&dir);
    }
}
